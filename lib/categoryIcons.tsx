// Fallback icon for unknown categories
const DEFAULT_ICON: IconType = MdLabel;

/**
 * Get the icon component for an expense category.
 * Matches case-insensitively; trims and normalizes the category string.
 *
 * @param category - Category name (e.g. "Food", "Healthcare", "Web Hosting")
 * @returns React icon component from react-icons
 *
 * @example
 * const Icon = getCategoryIcon('Food');
 * return <Icon className="w-6 h-6" />;
 */
export function getCategoryIcon(category: string): IconType {
  if (!category || typeof category !== 'string') return DEFAULT_ICON;
  const normalized = category.trim().toLowerCase();
  return CATEGORY_ICON_MAP[normalized] ?? DEFAULT_ICON;
}

